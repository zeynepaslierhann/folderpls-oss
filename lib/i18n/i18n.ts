// Helper function to get nested translation
function resolvePath(root: unknown, segments: readonly string[]): unknown {
  return segments.reduce<unknown>((node, segment) => (node as Record<string, unknown> | undefined)?.[segment], root);
}

export function getTranslation(locale: Locale, key: string): string {
  const segments = key.split(".");
  const found = resolvePath(translations[locale], segments) ?? resolvePath(translations.tr, segments);
  return typeof found === "string" ? found : key;
}
